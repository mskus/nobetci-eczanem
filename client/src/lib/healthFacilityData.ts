export function getFacilitiesByCity(
  city: string,
  district?: string,
  facilityType?: FacilityType | "all",
  userLoc?: { latitude: number; longitude: number } | null
): HealthFacility[] {
  const citySlug = toTurkishSlug(city);
  const isSpecificDistrict = Boolean(district && district !== "Tümü");
  const distSlug = isSpecificDistrict ? toTurkishSlug(district!) : "";

  // 1. Match static verified facilities for this city
  let list = VERIFIED_FACILITIES.filter((f) => toTurkishSlug(f.city) === citySlug);

  if (isSpecificDistrict) {
    list = list.filter((f) => toTurkishSlug(f.district) === distSlug);

    // Ensure every selected district has complete coverage across all 3 facility types
    const generatedForDist = generateDistrictFacilities(city, district!);
    const existingNames = new Set(list.map((f) => f.name.toLocaleLowerCase("tr-TR")));
    generatedForDist.forEach((genFac) => {
      if (!existingNames.has(genFac.name.toLocaleLowerCase("tr-TR"))) {
        list.push(genFac);
      }
    });
  } else {
    // Viewing all districts in the city: supplement with top districts so every city has rich hospitals + ASMs + cabins
    const cityDistricts = TURKEY_DISTRICTS[citySlug] || ["Merkez"];
    const topDistricts = cityDistricts.slice(0, Math.min(4, cityDistricts.length));

    // Also add provincial center Training & Research / State Hospital if not in VERIFIED_FACILITIES
    if (!list.some((f) => f.type === "hastane")) {
      const cCoords = TURKEY_CITY_COORDINATES[citySlug] || {
        lat: 39.9208,
        lng: 32.8541,
        areaCode: "0312",
      };
      list.push({
        id: `city-eah-${citySlug}`,
        name: `${city} Eğitim ve Araştırma Hastanesi`,
        type: "hastane",
        typeName: "Eğitim ve Araştırma Hastanesi (7/24 Acil)",
        city,
        district: topDistricts[0] || "Merkez",
        address: `Merkez Kampüsü Hastane Bulvarı No:1, ${topDistricts[0] || "Merkez"} / ${city}`,
        landmark: `${city} Valiliği & Şehirlerarası Bulvar Kavşağı`,
        phone: `${cCoords.areaCode} 214 00 00`,
        emergencyPhone: "112",
        is24Hours: true,
        services: [
          "7/24 Yetişkin & Çocuk Acil",
          "Yoğun Bakım",
          "Kardiyoloji",
          "Travma Merkezi",
          "MR / Tomografi",
        ],
        location: { latitude: cCoords.lat, longitude: cCoords.lng },
      });
    }

    topDistricts.forEach((dName, idx) => {
      const gen = generateDistrictFacilities(city, dName, idx);
      gen.forEach((g) => {
        if (!list.some((existing) => existing.name === g.name)) {
          list.push(g);
        }
      });
    });
  }

  // 2. Filter by category if requested
  if (facilityType && facilityType !== "all") {
    list = list.filter((f) => f.type === facilityType);
  }

  // 3. Determine accurate reference point (GPS if user is in selected city, otherwise district/city center)
  const useGps = isUserInSelectedCity(userLoc, citySlug);
  const fallbackCenter = getDistrictCoordinates(
    citySlug,
    isSpecificDistrict ? district : undefined
  );
  const refLat = useGps && userLoc ? userLoc.latitude : fallbackCenter.lat;
  const refLng = useGps && userLoc ? userLoc.longitude : fallbackCenter.lng;

  list = list.map((f) => ({
    ...f,
    distance: Number(
      calculateDistanceKm(refLat, refLng, f.location.latitude, f.location.longitude).toFixed(2)
    ),
  }));

  list.sort((a, b) => (a.distance ?? 999) - (b.distance ?? 999));

  return list;
}
