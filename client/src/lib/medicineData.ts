export interface MedicineItem {
  id: string;
  barcode: string;
  name: string;
  activeIngredient: string;
  category: MedicineCategory;
  prescriptionType:
    | "Reçetesiz (OTC - Serbest)"
    | "Reçeteli (Beyaz Reçete)"
    | "Yeşil Reçete (Kontrole Tabi)"
    | "Kırmızı Reçete (Narkotik)";
  isReimbursedBySGK: boolean;
  publicSalePrice: number; // KDV Dahil PSF (TL)
  publicBasePrice: number; // Kamu Taban Fiyatı (TL)
  patientCopayEstimated: number; // Emekli %10 Katkı Payı
  manufacturer: string;
  indications: string; // Ne işe yarar / Hangi hastalıklarda kullanılır
  usageInstructions: string; // Nasıl kullanılır (Aç/Tok, Doz)
  prescriptionWarning: string; // Reçete, SGK ve güvenlik açıklaması
}

function createMed(
  id: string,
  barcode: string,
  name: string,
  activeIngredient: string,
  category: MedicineCategory,
  prescriptionType: MedicineItem["prescriptionType"],
  isReimbursedBySGK: boolean,
  publicSalePrice: number,
  manufacturer: string,
  indications: string,
  usageInstructions: string,
  prescriptionWarning: string
): MedicineItem {
  const publicBasePrice = Number((publicSalePrice * 0.88).toFixed(2));
  const patientCopayEstimated = isReimbursedBySGK
    ? Number((publicSalePrice * 0.1).toFixed(2))
    : publicSalePrice;
  return {
    id,
    barcode,
    name,
    activeIngredient,
    category,
    prescriptionType,
    isReimbursedBySGK,
    publicSalePrice,
    publicBasePrice,
    patientCopayEstimated,
    manufacturer,
    indications,
    usageInstructions,
    prescriptionWarning,
  };
}

